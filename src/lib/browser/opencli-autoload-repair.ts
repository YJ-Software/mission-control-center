import { execFileSync, spawn } from 'child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'fs'
import os from 'os'
import path from 'path'
import { getBrowserConfig, getChromeBinaryPath } from './config'
import { getOpencliLoaderPath, shouldLoadExtensionViaCdp, writeOpencliLoader } from './opencli-extension'
import { isExecutableFile, nodePathCandidates, resolveNodePath } from './node-path'

/**
 * Repair the OpenCLI extension auto-load on boxes installed before it existed.
 *
 * Google Chrome drops a CDP-loaded extension on every restart, so the browser
 * unit carries an ExecStartPost that re-loads it (shipped in 0.3.82). Units are
 * written once at install time and `upgrade.sh` only re-renders Mission
 * Control's own unit — so a box whose browser stack predates 0.3.82 never gets
 * that line, and after the next Chrome restart every `opencli` browser command
 * fails with BROWSER_CONNECT. Nothing surfaces: the browser still runs, and the
 * features that quietly depend on it (morning-report sources, skills) just lose
 * content. Observed in the wild: a morning-report section missing for four days.
 *
 * The repair is a systemd drop-in, never a unit rewrite: re-rendering the unit
 * would also re-resolve ports, and an install that finds its own old ports busy
 * rotates them — moving the operator's VNC port out from under them.
 */

export const CHROME_UNIT = 'chrome-headless.service'

function userUnitDir(): string {
  return path.join(os.homedir(), '.config', 'systemd', 'user')
}

export function getAutoloadDropInPath(): string {
  return path.join(userUnitDir(), `${CHROME_UNIT}.d`, 'opencli-extension.conf')
}

function extensionDir(): string {
  return path.join(os.homedir(), '.opencli', 'extension')
}

function isExtensionInstalled(): boolean {
  return existsSync(path.join(extensionDir(), 'manifest.json'))
}

/** Reset the list so an obsolete loader in the base unit cannot still run.
 * Keep unrelated post-start commands, including their original failure policy. */
export function buildAutoloadDropIn(nodeBin: string, loaderPath: string, commands: string[] = []): string {
  return [
    '# Generated by Mission Control: re-loads the OpenCLI browser extension on',
    '# every Chrome start. Google Chrome forgets CDP-loaded extensions across',
    '# restarts. Safe to delete; the browser still runs without it.',
    '[Service]',
    'ExecStartPost=',
    ...commands.filter((command) => !loaderInvocation(command, loaderPath))
      .map((command) => `ExecStartPost=${command}`),
    `ExecStartPost=-${nodeBin} ${loaderPath}`,
    '',
  ].join('\n')
}

/** Apply systemd's list/reset semantics in unit then drop-in order. */
export function postStartCommands(texts: Array<string | null>): string[] {
  let commands: string[] = []
  for (const text of texts) {
    let service = false
    for (const raw of (text || '').split('\n')) {
      const line = raw.trim()
      if (line.startsWith('[')) service = line === '[Service]'
      if (!service || !line.startsWith('ExecStartPost=')) continue
      const command = line.slice('ExecStartPost='.length).trim()
      if (command) commands.push(command)
      else commands = []
    }
  }
  return commands
}

function loaderInvocation(command: string, loaderPath: string): { nodeBin: string; ignoresFailure: boolean } | null {
  // MCC writes an absolute interpreter followed by the loader. Also accept
  // quoted paths in units edited by an operator.
  const match = command.match(/^(-?)(?:"([^"]+)"|'([^']+)'|(\S+))\s+(?:"([^"]+)"|'([^']+)'|(\S+))(?:\s|$)/)
  if (!match || (match[5] || match[6] || match[7]) !== loaderPath) return null
  return { nodeBin: match[2] || match[3] || match[4], ignoresFailure: match[1] === '-' }
}

/** A present loader can still kill Chrome before the script gets to run. */
export function loaderNeedsRepair(commands: string[], loaderPath: string, executable: (file: string) => boolean): boolean {
  const loaders = commands.map((command) => loaderInvocation(command, loaderPath)).filter((loader) => loader !== null)
  return loaders.length === 0 || loaders.some((loader) =>
    !loader.ignoresFailure || nodePathCandidates(loader.nodeBin)[0] !== loader.nodeBin || !executable(loader.nodeBin),
  )
}

/** Whether a unit (or drop-in) text already runs this loader. */
export function unitRunsLoader(text: string | null | undefined, loaderPath: string): boolean {
  return postStartCommands([text ?? null]).some((command) => loaderInvocation(command, loaderPath) !== null)
}

export type RepairDecision =
  /** No browser stack on this box — nothing to repair. */
  | 'no-browser'
  /** Chromium takes the extension at launch, or the extension is not installed. */
  | 'not-applicable'
  /** The loader already runs on every Chrome start. */
  | 'configured'
  /** The loader is missing or unsafe — install/update the drop-in. */
  | 'repair'

export function decideAutoloadRepair(params: {
  unitExists: boolean
  runsLoader: boolean
  loaderNeedsRepair?: boolean
  chromeBin: string
  extensionInstalled: boolean
}): RepairDecision {
  if (!params.unitExists) return 'no-browser'
  if (!shouldLoadExtensionViaCdp(params.chromeBin, params.extensionInstalled)) return 'not-applicable'
  return params.runsLoader && !params.loaderNeedsRepair ? 'configured' : 'repair'
}

function readIfExists(file: string): string | null {
  try {
    return existsSync(file) ? readFileSync(file, 'utf8') : null
  } catch {
    return null
  }
}

function currentDecision(): { decision: RepairDecision; loaderPath: string; cdpPort: number; commands: string[] } {
  const loaderPath = getOpencliLoaderPath()
  const unitPath = path.join(userUnitDir(), CHROME_UNIT)
  const unitText = readIfExists(unitPath)
  const dropIn = getAutoloadDropInPath()
  const dropInDir = path.dirname(dropIn)
  // Our list reset must preserve hooks from earlier operator drop-ins too.
  // Later operator overrides remain authoritative, as they do in systemd.
  const dropIns = existsSync(dropInDir)
    ? readdirSync(dropInDir).filter((name) => name.endsWith('.conf') && name <= path.basename(dropIn)).sort()
    : []
  const commands = postStartCommands([unitText, ...dropIns.map((name) => readIfExists(path.join(dropInDir, name)))])
  return {
    loaderPath,
    commands,
    cdpPort: parseInt(getBrowserConfig('cdp_port') || '9222', 10),
    decision: decideAutoloadRepair({
      unitExists: unitText !== null,
      runsLoader: commands.some((command) => loaderInvocation(command, loaderPath) !== null),
      loaderNeedsRepair: loaderNeedsRepair(commands, loaderPath, isExecutableFile),
      chromeBin: getChromeBinaryPath() || '',
      extensionInstalled: isExtensionInstalled(),
    }),
  }
}

/** For the browser page and its E2E: does this box re-load the extension on every Chrome start? */
export function isAutoloadConfigured(): boolean {
  try {
    return currentDecision().decision !== 'repair'
  } catch {
    return false
  }
}

/**
 * Run at boot. Repairs missing or unsafe loader commands, then runs the loader
 * once so the running Chrome is fixed without waiting for a restart. The loader
 * is idempotent, so the same call is a cheap no-op on a healthy box. Never
 * throws: a browser repair must not be able to stop Mission Control booting.
 * Only daemon-reload, never restart Chrome: a running browser keeps its session.
 * An auto-restarting unit picks up the fix on its next attempt; a failed unit
 * with no pending restart remains stopped until the operator starts it.
 */
export function ensureOpencliAutoload(): RepairDecision {
  let decision: RepairDecision = 'no-browser'
  try {
    const current = currentDecision()
    decision = current.decision
    if (decision === 'no-browser' || decision === 'not-applicable') return decision

    let nodeBin = process.execPath
    if (decision === 'repair') {
      const oldLoader = current.commands.map((command) => loaderInvocation(command, current.loaderPath))
        .find((loader) => loader !== null)
      try {
        nodeBin = resolveNodePath(oldLoader?.nodeBin)
      } catch {
        nodeBin = resolveNodePath()
      }
      writeOpencliLoader(current.cdpPort, extensionDir())
      const dropIn = getAutoloadDropInPath()
      mkdirSync(path.dirname(dropIn), { recursive: true })
      writeFileSync(dropIn, buildAutoloadDropIn(nodeBin, current.loaderPath, current.commands), 'utf8')
      execFileSync('systemctl', ['--user', 'daemon-reload'], { timeout: 15_000 })
      console.log('[opencli-autoload] repaired ExecStartPost drop-in for', CHROME_UNIT)
    }

    // Heals the running Chrome too: after this the extension is loaded whether
    // the drop-in is brand new or an earlier ExecStartPost failed.
    //
    // Spawned, never execFileSync: the loader waits up to a minute for a CDP
    // endpoint that may never come up, and this runs inside Mission Control's
    // own startup — a synchronous call would block the event loop for that long
    // and leave the dashboard unresponsive on exactly the broken boxes this is
    // meant to repair.
    try {
      const child = spawn(nodeBin, [current.loaderPath], { stdio: 'inherit', detached: true })
      child.on('error', (err) => console.warn('[opencli-autoload] loader spawn failed:', err.message))
      child.unref()
    } catch (err) {
      console.warn('[opencli-autoload] loader spawn failed:', (err as Error).message)
    }

    if (decision === 'repair') notifyRepaired()
    return decision
  } catch (err) {
    console.warn('[opencli-autoload] check failed:', (err as Error).message)
    return decision
  }
}

function notifyRepaired(): void {
  // Dynamic import, and by relative path: the notification store pulls in the
  // database, while this module is also read by the browser status API — and
  // server.ts loads this file outside Next's bundler, where a `require` call or
  // an `@/` alias would not resolve and the notice would be lost silently.
  void import('../notifications')
    .then(({ createNotification }) => {
      createNotification({
        type: 'system',
        severity: 'info',
        title: '已修復瀏覽器擴充功能自動載入',
        body: 'Chrome 重新啟動後會自動載入 OpenCLI 擴充功能，opencli 的瀏覽器指令不會再因重啟而失效。',
        dedupKey: 'opencli-autoload-repaired',
      })
    })
    .catch((err: Error) => console.warn('[opencli-autoload] notification failed:', err.message))
}
