import { randomBytes } from 'node:crypto'
import { existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { BackendCapabilities } from './capabilities'

export function bootstrapEnvLocal(
  dir: string,
  capabilities: BackendCapabilities,
  findOpenClawToken: () => string,
): boolean {
  const file = join(dir, '.env.local')
  if (existsSync(file)) return false

  console.log('[Bootstrap] First run detected, generating .env.local ...')
  const password = randomBytes(16).toString('base64url')
  const secret = randomBytes(32).toString('base64url')
  const openclaw = capabilities.openclawSetup
  const gatewayToken = openclaw ? findOpenClawToken() : ''
  const lines = [
    '# Auto-generated by Mission Control on first run',
    '',
    ...(openclaw ? [
      '# OpenClaw Gateway',
      'OPENCLAW_GATEWAY_WS=ws://127.0.0.1:18789',
      'OPENCLAW_GATEWAY_HTTP=http://127.0.0.1:18789',
      `OPENCLAW_TOKEN=${gatewayToken}`,
      '',
    ] : ['MCC_AGENT_RUNTIME=hermes', '']),
    '# Authentication',
    `AUTH_PASSWORD=${password}`,
    `AUTH_SECRET=${secret}`,
    '',
    '# Server',
    'PORT=3737',
    'HOST=0.0.0.0',
    '',
  ]
  writeFileSync(file, lines.join('\n'), openclaw ? undefined : { mode: 0o600 })
  console.log('[Bootstrap] .env.local created')
  if (openclaw) {
    console.log(`[Bootstrap] Dashboard password: ${password}`)
    console.log('[Bootstrap] Save this password — it won\'t be shown again.')
    if (gatewayToken) console.log('[Bootstrap] Gateway token auto-detected from ~/.openclaw/openclaw.json')
    else console.warn('[Bootstrap] No gateway token found. Set it in Settings page or .env.local')
  } else {
    console.log('[Bootstrap] Dashboard password is stored in .env.local')
  }
  return true
}
